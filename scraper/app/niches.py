def current_season(month: int | None = None) -> dict:
    """Вернуть сезонный набор для месяца (1-12)."""
    from datetime import datetime

    if month is None:
        month = datetime.now().month
    for key, season in SEASONS.items():
        if month in season["months"]:
            return {"key": key, **season}
    return {"key": "autumn", **SEASONS["autumn"]}
